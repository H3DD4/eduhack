"""Candidate questions for a concept, described for the learner engine (ItemSpec) + how to build the task.

Sources (all labelled with their origin):
  * course exercises extracted from the student's upload          (unverified-source, declared "easy")
  * SymPy-checked algebra bank with difficulty + trigger tags       (ai-generated)
  * AI study-pack questions (easy / medium / hard)                  (ai-generated)
item_id is STABLE ACROSS STUDENTS (normalised expression / question hash) so anonymous quality statistics add up.
Trigger tags say which misconception a question would expose (e.g. any a(b + c) with ≥ 2 terms exposes
"multiplied only the first term"; a minus sign exposes "sign error").
"""

from __future__ import annotations

import hashlib
import re

from thinkfirst.modules.tutor import generators

ORIGIN_DETAIL = {
    "unverified-source": "Extracted from your upload (not verified)",
    "ai-generated": "Generated by ThinkFirst (template, checked with SymPy)",
}
# Never used as practice: the explanation prompt and the transfer targets must stay new for those stages.
RESERVED = {"3(x+4)", "5(x+2)", "4(x+3)"}
ALGEBRA_BANK = [  # (expression, difficulty)
    ("3(y + 5)", "easy"), ("4(a + 2)", "easy"), ("5(x + 1)", "easy"),
    ("2(x - 7)", "medium"), ("6(b - 3)", "medium"), ("-2(x + 4)", "medium"),
    ("-3(2x - 5)", "hard"), ("4(3y - 2)", "hard"), ("-5(2a - 3)", "hard"),
]


def norm(text: str) -> str:
    return re.sub(r"\s+", "", text.lower().replace("−", "-"))


def expand_key(expr: str) -> str:
    return f"expand:{norm(expr)}"


def text_key(prefix: str, text: str) -> str:
    return f"{prefix}:{hashlib.sha1(norm(text).encode()).hexdigest()[:12]}"


def expand_triggers(expr: str) -> list[str]:
    from thinkfirst.modules.diagnostic.grading.mathcheck import split_product

    sp = split_product(expr)
    out = []
    if sp is not None and len(sp.terms) >= 2:
        out.append("distribution_first_term_only")
    if "-" in expr.replace("−", "-"):
        out.append("sign_error")
    return out


def candidate_pool(db, s, concept) -> list[dict]:
    """[{spec: ItemSpec-json, build: task fields}] for this concept."""
    from thinkfirst.modules.rag.ingestion import service as ingestion

    pool: list[dict] = []
    order = 0
    if "distribut" in concept.title.lower() or any(i.kind == "expand" for i in ingestion.items_for(db, s.owner_id, s.subject_id, concept.key)):
        for it in ingestion.items_for(db, s.owner_id, s.subject_id, concept.key):
            if it.kind == "expand" and it.expression:
                pool.append(_expand(concept, it.expression, "easy", order, "unverified-source",
                                    f"{ORIGIN_DETAIL['unverified-source']} · page {it.page_no}"))
                order += 1
        if "distribut" in concept.title.lower():
            for expr, diff in ALGEBRA_BANK:
                if norm(expr) not in RESERVED:
                    pool.append(_expand(concept, expr, diff, order, "ai-generated", ORIGIN_DETAIL["ai-generated"]))
                    order += 1
        return _dedupe(pool)
    from thinkfirst.modules.tutor import packs

    pack = packs.get_pack(db, s.owner_id, s.concept_id)
    if pack is None or pack.status != "ready":
        return []
    for item in pack.content.get("practice", []):
        key = text_key("pack", item["prompt"])
        pool.append({"spec": {"item_id": key, "concept_id": concept.id, "difficulty": item.get("difficulty", "medium"),
                              "triggers": [], "order": order},
                     "build": {"kind": "expression" if item["answer_kind"] == "expression" else "short_answer",
                               "prompt": item["prompt"], "origin": "ai-generated",
                               "origin_detail": f"Generated study pack — {pack.label}", "family": f"pack:{concept.key}",
                               "solution": {"expected": item["expected_answer"], "steps": item["hints"][-1]},
                               "hints": item["hints"]}})
        order += 1
    return _dedupe(pool)


def _expand(concept, expr: str, difficulty: str, order: int, origin: str, detail: str) -> dict:
    hints, sol = generators.expand_hints(expr)
    return {"spec": {"item_id": expand_key(expr), "concept_id": concept.id, "difficulty": difficulty,
                     "triggers": expand_triggers(expr), "order": order},
            "build": {"kind": "expand", "prompt": f"Expand {expr}.", "origin": origin, "origin_detail": detail,
                      "family": f"expand:{concept.key}", "solution": {"expression": expr, **sol}, "hints": hints}}


def _dedupe(pool: list[dict]) -> list[dict]:
    seen, out = set(), []
    for p in pool:
        if p["spec"]["item_id"] not in seen:
            seen.add(p["spec"]["item_id"])
            out.append(p)
    return out
