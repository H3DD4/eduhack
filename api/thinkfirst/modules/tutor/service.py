# ------------------------------------------------------------------ sessions

def create_session(db: Session, owner_id: str, subject_id: str, concept_id: str, kind: str = "learn",
                   parent_session_id: str | None = None) -> StudySession:
    if kind not in STAGES:
        raise ValidationFailed("Choose Learn or Practice.", field="kind")
    subject = workspaces.get_subject(db, owner_id, subject_id)
    concept = ingestion.get_concept(db, owner_id, concept_id)
    if subject.status != "ready" or concept.subject_id != subject.id:
        raise NotFound("This concept is not part of a confirmed scope.")
    s = StudySession(owner_id=owner_id, subject_id=subject_id, concept_id=concept_id, concept_key=concept.key,
                     graph_revision_id=concept.graph_revision_id, kind=kind, parent_session_id=parent_session_id,
                     config={"input_mode": "text", "focus_quiet": False, "timer_minutes": None})
    db.add(s)
    db.flush()
    workspaces.set_last_concept(db, owner_id, subject_id, concept_id)
    return s


def get_session(db: Session, owner_id: str, session_id: str) -> StudySession:
    return get_owned(db, StudySession, session_id, owner_id)


def get_task(db: Session, owner_id: str, task_id: str) -> Task:
    return get_owned(db, Task, task_id, owner_id)


def _locked_task(db: Session, task: Task) -> Task:
    """Row lock (Postgres FOR UPDATE) so assessment/conversion commits serialize by revision."""
    if db.get_bind().dialect.name == "postgresql":
        db.execute(select(Task).where(Task.id == task.id).with_for_update())
        db.refresh(task)
    return task


def start_session(db: Session, owner_id: str, session_id: str, config: dict, idempotency_key: str) -> StudySession:
    s = get_session(db, owner_id, session_id)
    if s.status != "draft":
        return s
    allowed = {"input_mode": {"text", "voice"}, "focus_quiet": {True, False}}
    for k, v in config.items():
        if k in allowed and v in allowed[k]:
            s.config = {**s.config, k: v}
        elif k == "timer_minutes" and (v is None or (isinstance(v, int) and 5 <= v <= 120)):
            s.config = {**s.config, k: v}
    # Reserve the whole validation bundle (explanation + follow-up + transfer) BEFORE starting (override §3.11).
    units = get_settings().validation_bundle_units
    res = billing.reserve(db, owner_id, "validation_bundle", units, idempotency_key=f"bundle:{s.id}:{idempotency_key}",
                          purpose_ref=s.id, intent={"kind": "start_session", "session_id": s.id, "subject_id": s.subject_id})
    s.reservation_id = res.id
    s.status = "active"
    s.stage = STAGES[s.kind][0]
    s.revision += 1
    _enter_stage(db, s)
    return s


def acquire_lease(db: Session, owner_id: str, session_id: str, device_id: str, takeover: bool) -> StudySession:
    s = get_session(db, owner_id, session_id)
    now = utcnow()
    held = s.lease_token and s.lease_expires_at and s.lease_expires_at > now and s.lease_device != device_id
    if held and not takeover:
        raise LeaseHeld("Another session has newer work. Open read-only or take over.",
                        lease_expires_at=s.lease_expires_at.isoformat() if s.lease_expires_at else None)
    s.lease_token = secrets.token_urlsafe(24)
    s.lease_device = device_id[:64]
    s.lease_expires_at = now + timedelta(minutes=LEASE_MINUTES)
    return s


def _check_lease(s: StudySession, lease_token: str | None) -> None:
    if not lease_token or lease_token != s.lease_token:
        raise LeaseHeld("This device no longer holds the session. Your local draft is kept separately.",
                        code="LEASE_LOST")


def save_checkpoint(db: Session, owner_id: str, session_id: str, expected_revision: int, lease_token: str | None,
                    checkpoint: dict) -> StudySession:
    s = get_session(db, owner_id, session_id)
    _check_lease(s, lease_token)
    if expected_revision != s.revision:
        raise StaleRevision(current_revision=s.revision)
    allowed = {"drafts", "phase", "return_phase", "cursor", "recall_text", "selected_draft"}
    s.checkpoint = {**s.checkpoint, **{k: v for k, v in checkpoint.items() if k in allowed}}
    s.revision += 1
    s.lease_expires_at = utcnow() + timedelta(minutes=LEASE_MINUTES)
    return s


def pause(db: Session, owner_id: str, session_id: str, expected_revision: int, lease_token: str | None,
          checkpoint: dict) -> StudySession:
    s = save_checkpoint(db, owner_id, session_id, expected_revision, lease_token, checkpoint)
    if s.status == "active":
        s.status = "paused"  # the no-help lock is task state, so pausing never lifts it
    return s


def resume(db: Session, owner_id: str, session_id: str, lease_token: str | None) -> StudySession:
    s = get_session(db, owner_id, session_id)
    _check_lease(s, lease_token)
    if s.status == "paused":
        s.status = "active"
        s.revision += 1
    return s


def advance(db: Session, owner_id: str, session_id: str, expected_revision: int) -> StudySession:
    s = get_session(db, owner_id, session_id)
    if s.status not in ("active",):
        raise Conflict("Resume the session first.", code="SESSION_NOT_ACTIVE")
    if expected_revision != s.revision:
        raise StaleRevision(current_revision=s.revision)
    current = current_task(db, s)
    if s.stage == "transfer" and current is not None and current.status not in policy.TERMINAL_TASK:
        raise Conflict("Finish or set aside the application task first.", code="TRANSFER_NOT_FINISHED")
    if s.stage in ("explanation", "followup") and current is not None and not _has_assessment(db, current):
        raise Conflict("Confirm and check your explanation first, or save and leave.", code="STAGE_NOT_FINISHED")
    order = STAGES[s.kind]
    if s.stage == "learn":
        concept = ingestion.get_concept(db, owner_id, s.concept_id)
        events.publish(db, events.Event(learner.EXPOSURE_RECORDED, owner_id, {
            "subject_id": s.subject_id, "concept_id": s.concept_id, "concept_key": concept.key,
            "session_id": s.id, "stage": "learn", "summary": "Read the cited course section and worked example."}))
    idx = order.index(s.stage)
    s.stage = order[min(idx + 1, len(order) - 1)]
    s.revision += 1
    s.checkpoint = {**s.checkpoint, "phase": None, "return_phase": None}
    _enter_stage(db, s)
    return s


def _has_assessment(db: Session, task: Task) -> bool:
    return any(assessment.assessment_for_attempt(db, a.id) for a in assessment.attempts_for_task(db, task.owner_id, task.id))


def tasks_of(db: Session, s: StudySession) -> list[Task]:
    return list(db.scalars(select(Task).where(Task.session_id == s.id).order_by(Task.created_at)).all())


def current_task(db: Session, s: StudySession) -> Task | None:
    stage_tasks = [t for t in tasks_of(db, s) if t.stage == s.stage]
    return stage_tasks[-1] if stage_tasks else None


def _enter_stage(db: Session, s: StudySession) -> None:
    if s.stage == "practice":
        _create_practice_task(db, s)
    elif s.stage == "explanation":
        _create_explanation_task(db, s)
    elif s.stage == "followup":
        expl = next((t for t in tasks_of(db, s) if t.stage == "explanation"), None)
        if expl is not None:
            jobs.enqueue(db, "tutor.generate_followup", s.owner_id, {"session_id": s.id, "explanation_task_id": expl.id},
                         idempotency_key=f"followup:{expl.id}")
    elif s.stage == "transfer":
        jobs.enqueue(db, "tutor.prepare_transfer", s.owner_id, {"session_id": s.id},
                     idempotency_key=f"transfer:{s.id}")


def _concept(db: Session, s: StudySession):
    return ingestion.get_concept(db, s.owner_id, s.concept_id)


def _create_practice_task(db: Session, s: StudySession, parent: Task | None = None) -> Task | None:
    concept = _concept(db, s)
    used = [t.solution.get("expression", "") for t in tasks_of(db, s) if t.stage == "practice"]
    items = [i for i in ingestion.items_for(db, s.owner_id, s.subject_id, concept.key)
             if i.kind == "expand" and i.expression and i.expression not in used]
    if items and parent is None:
        it = items[0]
        expr, origin, detail = it.expression, "unverified-source", f"{ORIGIN_DETAIL['unverified-source']} · page {it.page_no}"
        prompt = f"Expand {expr}."
    elif "distribut" in concept.title.lower():
        expr = generators.expand_variant(used + [i.expression for i in items if i.expression])
        if expr is None:
            return None
        origin, detail, prompt = "ai-generated", ORIGIN_DETAIL["ai-generated"], f"Expand {expr}."
    else:
        return None
    hints, sol = generators.expand_hints(expr)
    t = Task(owner_id=s.owner_id, session_id=s.id, subject_id=s.subject_id, stage="practice", kind="expand",
             prompt=prompt, origin=origin, origin_detail=detail, task_family_id=f"expand:{concept.key}",
             context={"objective": concept.objective}, solution={"expression": expr, **sol}, hints=hints,
             mode="practice", parent_task_id=parent.id if parent else None)
    db.add(t)
    db.flush()
    return t


def _create_explanation_task(db: Session, s: StudySession) -> Task:
    concept = _concept(db, s)
    rubric = assessment.get_rubric(db, s.owner_id, s.subject_id, concept.key, concept.title)
    t = Task(owner_id=s.owner_id, session_id=s.id, subject_id=s.subject_id, stage="explanation", kind="explain",
             prompt=rubric.explain_prompt, origin="ai-generated",
             origin_detail="Prompt from a demo rubric template (not from your course)",
             task_family_id=f"explain:{concept.key}", rubric_id=rubric.id, hints=generators.EXPLAIN_HINTS,
             context={"objective": concept.objective, "rubric": assessment.rubric_public(rubric)}, mode="practice")
    db.add(t)
    db.flush()
    return t


@jobs.job_handler("tutor.generate_followup")
def _followup_job(db: Session, job: jobs.Job) -> dict:
    s = db.get(StudySession, job.payload["session_id"])
    expl = db.get(Task, job.payload["explanation_task_id"])
    if s is None or expl is None:
        raise jobs.JobError("MISSING")
    existing = db.scalar(select(Task).where(Task.session_id == s.id, Task.stage == "followup"))
    if existing:
        return {"task_id": existing.id}  # retry returns the same question, never a reroll
    rubric = assessment.get_rubric(db, s.owner_id, s.subject_id, s.concept_key)
    attempts = assessment.attempts_for_task(db, s.owner_id, expl.id)
    a = assessment.assessment_for_attempt(db, attempts[-1].id) if attempts else None
    from thinkfirst.modules.assessment.explanation import choose_followup

    fu = choose_followup(a.criteria if a else [], rubric.followup_bank)
    t = Task(owner_id=s.owner_id, session_id=s.id, subject_id=s.subject_id, stage="followup", kind="explain",
             prompt=fu["question"], origin="ai-generated", origin_detail="Follow-up chosen from the demo rubric bank",
             task_family_id=f"followup:{s.concept_key}", rubric_id=rubric.id, hints=generators.EXPLAIN_HINTS[:2],
             followup_question_id=fu["id"], targets_criterion=fu["targets_criterion"],
             context={"targets_criterion": fu["targets_criterion"], "rubric": assessment.rubric_public(rubric)})
    db.add(t)
    db.flush()
    _charge(db, s, "followup")
    return {"task_id": t.id}


@jobs.job_handler("tutor.prepare_transfer")
def _transfer_job(db: Session, job: jobs.Job) -> dict:
    s = db.get(StudySession, job.payload["session_id"])
    if s is None:
        raise jobs.JobError("MISSING")
    existing = db.scalar(select(Task).where(Task.session_id == s.id, Task.stage == "transfer"))
    if existing:
        return {"task_id": existing.id}
    concept = ingestion.get_concept(db, s.owner_id, s.concept_id)
    if "distribut" not in concept.title.lower():
        return {"task_id": None, "unavailable": "No validated application task exists for this concept yet."}
    exclude = [t.solution.get("expression", "") for t in tasks_of(db, s) if t.stage == "practice"]
    exclude += [i.expression for i in ingestion.all_items(db, s.owner_id, s.subject_id) if i.expression]
    exclude += ["2(x + 3)", "5(a - 1)", "3(x + 2)"]  # expressions used in the explanation prompt/course examples
    spec = generators.transfer_task([e for e in exclude if e])
    if spec is None:
        return {"task_id": None, "unavailable": "No sufficiently new application task could be validated."}
    t = Task(owner_id=s.owner_id, session_id=s.id, subject_id=s.subject_id, stage="transfer", kind="equivalent_forms",
             prompt=spec["prompt"], origin="ai-generated", origin_detail=ORIGIN_DETAIL["ai-generated"],
             task_family_id=spec["family"], novelty=spec["novelty"], solution={"target": spec["target"], **spec["solution"]},
             mode="pending-commit", context={"criteria": ["correctness", "essential_coverage", "example_application"]},
             hints=["“Two equivalent forms” means two different-looking expressions that give the same total for every x.",
                    "Strategy: one form can keep each pack/row grouped; the other counts everything separately.",
                    "First sub-step: write the amount in ONE group, then say how many groups there are."])
    db.add(t)
    db.flush()
    _charge(db, s, "transfer")
    return {"task_id": t.id}


def _charge(db: Session, s: StudySession, reason: str) -> None:
    res = billing.get_reservation(db, s.owner_id, s.reservation_id)
    if res is not None:
        billing.consume(db, res, 1, reason, idempotency_key=f"charge:{s.id}:{reason}")


# ------------------------------------------------------------------ transfer mode / lock

def commit_mode(db: Session, owner_id: str, task_id: str, mode: str, expected_revision: int) -> Task:
    t = _locked_task(db, get_task(db, owner_id, task_id))
    if t.stage != "transfer" or t.mode != "pending-commit":
        raise Conflict("The mode for this task is already committed.", code="MODE_ALREADY_COMMITTED")
    if expected_revision != t.revision:
        raise StaleRevision(current_revision=t.revision)
    if mode not in ("independent", "guided"):
        raise ValidationFailed("Choose independent or guided.", field="mode")
    t.mode = "independent-transfer" if mode == "independent" else "guided-transfer"
    t.revision += 1
    return t


def convert_to_guided(db: Session, owner_id: str, task_id: str, expected_revision: int) -> Task:
    """'Keep your work and switch to guided practice?' — irreversible, revision-serialized."""
    t = _locked_task(db, get_task(db, owner_id, task_id))
    if t.mode != "independent-transfer":
        raise Conflict("Only an independent attempt can be converted.", code="NOT_INDEPENDENT")
    if t.status in policy.TERMINAL_TASK:
        raise Conflict("This attempt already finished; its evidence is committed.", code="TASK_FINISHED")
    if expected_revision != t.revision:
        raise StaleRevision(current_revision=t.revision)
    t.mode = "guided-transfer"
    t.revision += 1
    events.publish(db, events.Event(events.CONVERSION_COMMITTED, owner_id, {"task_id": t.id, "revision": t.revision}))
    return t


def abandon(db: Session, owner_id: str, task_id: str) -> Task:
    t = get_task(db, owner_id, task_id)
    if t.status not in policy.TERMINAL_TASK:
        t.status = "abandoned"
        t.revision += 1
    return t


# ------------------------------------------------------------------ help ladder (P01)

def help_step(db: Session, owner_id: str, task_id: str, kind: str, confirm_reveal: bool, idempotency_key: str) -> dict:
    t = get_task(db, owner_id, task_id)
    prior = db.scalar(select(HelpEvent).where(HelpEvent.idempotency_key == f"help:{t.id}:{idempotency_key}"))
    if prior:
        return _help_payload(t, prior)
    if t.mode == "independent-transfer" and t.status not in policy.TERMINAL_TASK:
        raise policy.lock_error(t)
    policy.assert_unlocked(db, owner_id, t.subject_id)  # also blocks help on other tasks from a 2nd tab
    if t.mode == "pending-commit":
        raise Conflict("Choose how to attempt this task first.", code="MODE_NOT_COMMITTED")
    if t.status in ("ended_assisted", "abandoned"):
        raise Conflict("This attempt has ended. Try the fresh check.", code="TASK_FINISHED")
    level = policy.next_level(t, kind, confirm_reveal)
    step = generators.LADDER[level - 1]
    content = t.hints[level - 1] if level - 1 < len(t.hints) else "No further step is available."
    ev = HelpEvent(owner_id=owner_id, task_id=t.id, level=level, kind=step, content=content,
                   idempotency_key=f"help:{t.id}:{idempotency_key}")
    db.add(ev)
    t.help_level = max(t.help_level, level)
    fresh = None
    if step == "reveal":
        t.revealed = True
        t.status = "ended_assisted"  # a revealed target never becomes independent success
        t.revision += 1
        s = db.get(StudySession, t.session_id)
        if s is not None and t.stage == "practice":
            fresh = _create_practice_task(db, s, parent=t)
    db.flush()
    payload = _help_payload(t, ev)
    if fresh is not None:
        payload["fresh_task_id"] = fresh.id
    return payload


def _help_payload(t: Task, ev: HelpEvent) -> dict:
    return {"task_id": t.id, "level": ev.level, "step": ev.kind, "label": generators.LADDER_LABELS.get(ev.kind, ev.kind),
            "content": ev.content, "citations": ev.citations, "revealed": t.revealed, "help_level": t.help_level,
            "next_requires_confirmation": t.help_level == 4 and t.kind == "expand",
            "max_level": 5 if t.kind == "expand" else 3}


@register_demo("professor_scaffold")
def _demo_professor(v: dict) -> dict:
    chunks = v.get("course_chunks", [])
    if not chunks or not v.get("on_topic_hint", True):
        return {"message": "That question looks outside this subject's sources. Choose a concept in the Roadmap to ask about it.",
                "citations": [], "on_topic": False}
    top = chunks[0]
    first = top["text"].split("\n")[0][:220]
    return {"message": (f"Your course (page {top['page']}) says: “{first}”. "
                        "Try connecting that to the step you are on, then attempt it yourself."),
            "citations": [top["chunk_id"]], "on_topic": True}


def professor_ask(db: Session, owner_id: str, subject_id: str, question: str, task_id: str | None,
                  idempotency_key: str) -> dict:
    workspaces.get_subject(db, owner_id, subject_id)
    policy.assert_unlocked(db, owner_id, subject_id)
    task = get_task(db, owner_id, task_id) if task_id else None
    if task is not None and task.mode == "independent-transfer" and task.status not in policy.TERMINAL_TASK:
        raise policy.lock_error(task)
    question = (question or "").strip()[:1000]
    if not question:
        raise ValidationFailed("Type a question.", field="question")
    prior = db.scalar(select(HelpEvent).where(HelpEvent.idempotency_key == f"prof:{idempotency_key}"))
    if prior:
        return {"message": prior.content, "citations": prior.citations, "on_topic": bool(prior.citations), "replayed": True}
    res_q = billing.reserve(db, owner_id, "professor_question", 1, idempotency_key=f"prof:{idempotency_key}",
                            intent={"kind": "professor_question", "subject_id": subject_id})
    hits = ingestion.retrieve(db, owner_id, subject_id, question + " " + (task.prompt if task else ""), k=3)
    chunks = [{"chunk_id": c.id, "page": c.page_no, "text": c.text, "score": round(sc, 3)} for sc, c in hits]
    on_topic = bool(chunks) and chunks[0]["score"] >= 0.12
    result = llm.run(db, "professor_scaffold", {"student_question": question, "course_chunks": chunks if on_topic else [],
                                                "help_level": "strategy", "task_prompt": task.prompt if task else "",
                                                "on_topic_hint": on_topic}, owner_id=owner_id, purpose="professor")
    out = result.output if result.status == "ok" and result.output else {
        "message": "The Professor is unavailable right now. The help steps still work.", "citations": [], "on_topic": True}
    valid_ids = {c["chunk_id"] for c in chunks}
    cites = [c for c in chunks if c["chunk_id"] in set(out.get("citations", [])) & valid_ids]
    message = str(out.get("message", ""))[:2000]
    if task is not None and task.solution and not task.revealed:
        hidden = [str(task.solution.get(k, "")) for k in ("expanded", "target")]
        if any(h and h.replace(" ", "") in message.replace(" ", "") for h in hidden):
            message = "I can't give the final answer to your current task, but the help steps can guide the next move."
    citations = [{"chunk_id": c["chunk_id"], "page": c["page"], "quote": c["text"][:240]} for c in cites]
    db.add(HelpEvent(owner_id=owner_id, task_id=task.id if task else "none", level=0, kind="professor",
                     content=message, citations=citations, idempotency_key=f"prof:{idempotency_key}"))
    billing.consume(db, res_q, 1, "professor_question", idempotency_key=f"charge:prof:{idempotency_key}")
    return {"message": message, "citations": citations, "on_topic": bool(out.get("on_topic", on_topic)),
            "label": result.label, "simulated": result.simulated}


# ------------------------------------------------------------------ submissions

def _assistance(db: Session, t: Task) -> dict:
    helps = db.scalars(select(HelpEvent).where(HelpEvent.task_id == t.id)).all()
    return {"help_level": t.help_level, "help_steps": sorted({h.kind for h in helps}), "revealed": t.revealed,
            "corrective_feedback": t.corrective_feedback_shown, "conversion": t.mode == "guided-transfer",
            "student_reported": "unknown",
            "note": "Completed without in-app help" if t.mode == "independent-transfer" else None}


def _publish(db: Session, s: StudySession, t: Task, attempt, a, stage: str) -> None:
    events.publish(db, events.Event(events.ASSESSMENT_ACCEPTED, s.owner_id, {
        "subject_id": s.subject_id, "concept_id": s.concept_id, "concept_key": s.concept_key, "session_id": s.id,
        "task_id": t.id, "attempt_id": attempt.id, "assessment_id": a.id, "stage": stage,
        "mode": attempt.mode_at_submit, "outcome": a.outcome, "criteria": a.criteria, "assistance": _assistance(db, t),
        "origin": t.origin, "method_label": a.method_label, "summary": a.feedback}))


def submit_answer(db: Session, owner_id: str, task_id: str, answer: str, expected_revision: int,
                  idempotency_key: str) -> dict:
    """Typed answers for practice (expand) and transfer (equivalent forms). Idempotent per key."""
    t = _locked_task(db, get_task(db, owner_id, task_id))
    key = f"attempt:{t.id}:{idempotency_key}"
    replay = db.scalar(select(assessment.Attempt).where(assessment.Attempt.idempotency_key == key))
    if replay is not None:
        return {"task": task_public(db, t), "assessment": assessment.assessment_public(
            assessment.assessment_for_attempt(db, replay.id)), "replayed": True}
    if t.kind not in ("expand", "equivalent_forms"):
        raise ValidationFailed("Use the explanation flow for this task.")
    if t.status in policy.TERMINAL_TASK:
        raise Conflict("This attempt already finished.", code="TASK_FINISHED")
    if t.mode == "pending-commit":
        raise Conflict("Choose how to attempt this task first.", code="MODE_NOT_COMMITTED")
    if expected_revision != t.revision:
        raise StaleRevision(current_revision=t.revision, mode=t.mode)
    answer = (answer or "").strip()
    if not answer:
        raise ValidationFailed("Add text to check it.", field="answer")
    s = get_session(db, owner_id, t.session_id)
    attempt, _ = assessment.record_attempt(db, owner_id=owner_id, task_id=t.id, session_id=s.id, task_revision=t.revision,
                                           response_kind="text", response_text=answer[:2000], mode=t.mode,
                                           idempotency_key=key)
    if t.kind == "expand":
        result = mathcheck.grade_expand(answer, t.solution["expression"])
    else:
        result = mathcheck.grade_equivalent_forms(answer, t.solution["target"])
    a = assessment.save_symbolic(db, attempt, result)
    t.revision += 1
    if t.kind == "expand":
        if result.outcome == "demonstrated":
            t.status = "committed"
        elif result.outcome in ("not_demonstrated", "partial"):
            t.corrective_feedback_shown = True
    else:
        if result.outcome != "unscored":
            t.status = "committed"  # terminal: unlocks; submission alone of an unscored answer does not
    _publish(db, s, t, attempt, a, t.stage)
    return {"task": task_public(db, t), "assessment": assessment.assessment_public(a), "replayed": False}


def keep_unscored(db: Session, owner_id: str, task_id: str) -> Task:
    t = get_task(db, owner_id, task_id)
    if t.status not in policy.TERMINAL_TASK:
        t.status = "committed"
        t.revision += 1
    return t


def submit_confirmed_explanation(db: Session, owner_id: str, task_id: str, *, text: str, supplement: str | None,
                                 transcript_version_id: str | None, unresolved_spans: list[dict], response_kind: str,
                                 idempotency_key: str) -> dict:
    """Called by explain_back after transcript confirmation. Grades ONLY the confirmed revision."""
    t = get_task(db, owner_id, task_id)
    if t.kind != "explain":
        raise ValidationFailed("This task is not an explanation.")
    s = get_session(db, owner_id, t.session_id)
    key = f"explain:{t.id}:{idempotency_key}"
    attempt, created = assessment.record_attempt(db, owner_id=owner_id, task_id=t.id, session_id=s.id,
                                                 task_revision=t.revision, response_kind=response_kind,
                                                 response_text=text, supplement_text=supplement, mode=t.mode,
                                                 transcript_version_id=transcript_version_id, idempotency_key=key)
    if created:
        t.revision += 1
    job = jobs.enqueue(db, "tutor.assess_explanation", owner_id,
                       {"attempt_id": attempt.id, "task_id": t.id, "unresolved_spans": unresolved_spans},
                       idempotency_key=f"assess:{attempt.id}")
    return {"attempt_id": attempt.id, "job": jobs.job_public(job)}


@jobs.job_handler("tutor.assess_explanation")
def _assess_job(db: Session, job: jobs.Job) -> dict:
    from thinkfirst.modules.assessment.explanation import split_sentences

    attempt = db.get(assessment.Attempt, job.payload["attempt_id"])
    t = db.get(Task, job.payload["task_id"])
    if attempt is None or t is None or attempt.status == "deleted":
        return {"stale": True}
    s = db.get(StudySession, t.session_id)
    assert s is not None
    rubric = assessment.get_rubric(db, s.owner_id, s.subject_id, s.concept_key)
    sentences = split_sentences(attempt.response_text or "") + split_sentences(attempt.supplement_text or "", prefix="sup")
    concept = ingestion.get_concept(db, s.owner_id, s.concept_id)
    excerpt = ingestion.concept_excerpt(db, s.owner_id, concept)
    only = {t.targets_criterion, "correctness"} if t.stage == "followup" and t.targets_criterion else None
    a = assessment.assess_explanation(db, attempt, rubric, sentences=sentences,
                                      unresolved_spans=job.payload.get("unresolved_spans", []),
                                      course_excerpt=(excerpt or {}).get("text"), only_criteria=only)
    _publish(db, s, t, attempt, a, t.stage)
    if t.stage == "explanation":
        _charge(db, s, "explanation")
    t.status = "committed"
    return {"assessment_id": a.id, "attempt_id": attempt.id}


