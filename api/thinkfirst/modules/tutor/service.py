def task_public(db: Session, t: Task, hide_feedback: bool = False) -> dict:
    """Never includes solution/hints beyond what was disclosed; transfer prompt hidden until mode commit."""
    helps = db.scalars(select(HelpEvent).where(HelpEvent.task_id == t.id).order_by(HelpEvent.created_at)).all()
    attempts = assessment.attempts_for_task(db, t.owner_id, t.id)
    last = attempts[-1] if attempts else None
    last_a = assessment.assessment_for_attempt(db, last.id) if last else None
    return {
        "id": t.id, "session_id": t.session_id, "stage": t.stage, "kind": t.kind,
        "prompt": t.prompt if t.mode != "pending-commit" else None,
        "context": t.context, "origin": t.origin, "origin_detail": t.origin_detail, "task_family_id": t.task_family_id,
        "novelty": t.novelty if t.stage == "transfer" else None, "mode": t.mode, "status": t.status,
        "revision": t.revision, "help_level": t.help_level, "revealed": t.revealed,
        "max_help_level": 5 if t.kind == "expand" else 3, "targets_criterion": t.targets_criterion,
        "followup_question_id": t.followup_question_id,
        "help_events": [] if hide_feedback else [{"level": h.level, "step": h.kind,
                                                  "label": generators.LADDER_LABELS.get(h.kind, h.kind),
                                                  "content": h.content, "citations": h.citations} for h in helps],
        "solution": t.solution if t.revealed else None,
        "last_attempt": None if not last or hide_feedback else {"id": last.id, "response_text": last.response_text,
                                                                "supplement_text": last.supplement_text,
                                                                "status": last.status},
        "last_assessment": None if hide_feedback else assessment.assessment_public(last_a),
        "attempt_count": len(attempts),
    }


def session_view(db: Session, owner_id: str, session_id: str) -> dict:
    s = get_session(db, owner_id, session_id)
    concept = ingestion.get_concept(db, owner_id, s.concept_id)
    lock = policy.active_lock(db, owner_id, s.subject_id)
    tasks = tasks_of(db, s)
    cur = current_task(db, s)
    view: dict = {"session": session_public(s), "concept": ingestion.concept_public(concept),
                  "lock": {"task_id": lock.id, "session_id": lock.session_id} if lock else None,
                  "capabilities": policy.capabilities(cur, lock), "quota": billing.status(db, owner_id),
                  "provider": llm.capabilities()}
    hide = lock is not None
    view["tasks"] = [task_public(db, t, hide_feedback=hide and t.id != (lock.id if lock else None)) for t in tasks]
    view["current_task"] = task_public(db, cur, hide_feedback=hide and cur.id != lock.id) if cur and lock else (
        task_public(db, cur) if cur else None)
    if s.stage == "learn" and not hide:
        view["lesson"] = {"excerpt": ingestion.concept_excerpt(db, owner_id, concept),
                          "example": {"text": "Worked example from a different expression: 4(y − 2) = 4·y − 4·2 = 4y − 8.",
                                      "origin": "ai-generated"} if "distribut" in concept.title.lower() else None,
                          "retrieval_prompt": "Before moving on: in your own words, what happens to each term inside the brackets?"}
    elif s.stage == "learn":
        view["lesson"] = {"locked": True}
    pending = None
    if s.stage in ("followup", "transfer") and cur is None:
        key = f"followup:{next((t.id for t in tasks if t.stage == 'explanation'), '')}" if s.stage == "followup" else f"transfer:{s.id}"
        job = db.scalar(select(jobs.Job).where(jobs.Job.idempotency_key == key))
        pending = jobs.job_public(job) if job else None
    view["pending_job"] = pending
    return view
