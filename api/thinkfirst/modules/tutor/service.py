def save_reflection(db: Session, owner_id: str, session_id: str, text: str, skipped: bool) -> Reflection:
    s = get_session(db, owner_id, session_id)
    existing = db.scalar(select(Reflection).where(Reflection.session_id == s.id))
    if existing:
        return existing  # saved once; returning shows it, never asks again
    r = Reflection(owner_id=owner_id, session_id=s.id, text=(text or "")[:2000], skipped=skipped)
    db.add(r)
    db.flush()
    return r


